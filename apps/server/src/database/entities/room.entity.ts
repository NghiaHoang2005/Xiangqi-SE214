import {
  ROOM_STATUSES,
  SIDE_PREFERENCES,
  type RoomStatus,
  type SidePreference,
  type TimeControl,
} from '@xiangqi/shared';
import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  OneToMany,
  PrimaryColumn,
} from 'typeorm';
import { GuestSession } from './guest-session.entity';
import { RoomSeat } from './room-seat.entity';

/**
 * Private PVP waiting room (UC-03, UC-04). roomId carries at least 128 bits of entropy (NFR-10);
 * joinCode is the 8-character code players type (CFG-06). Closes after 30 idle minutes.
 */
@Entity({ name: 'room' })
export class Room {
  /** base64url of 16+ random bytes, generated by the room service. */
  @PrimaryColumn({ name: 'room_id', type: 'varchar', length: 43 })
  roomId!: string;

  @Index({ unique: true })
  @Column({ name: 'join_code', type: 'char', length: 8 })
  joinCode!: string;

  @Column({ type: 'enum', enum: ROOM_STATUSES, enumName: 'room_status', default: 'WAITING' })
  status!: RoomStatus;

  @Column({ name: 'time_control', type: 'jsonb' })
  timeControl!: TimeControl;

  @Column({
    name: 'preferred_side',
    type: 'enum',
    enum: SIDE_PREFERENCES,
    enumName: 'side_preference',
  })
  preferredSide!: SidePreference;

  @Column({ name: 'host_guest_id', type: 'uuid' })
  hostGuestId!: string;

  @ManyToOne(() => GuestSession, { onDelete: 'CASCADE' })
  @JoinColumn({ name: 'host_guest_id' })
  host?: GuestSession;

  @OneToMany(() => RoomSeat, (seat) => seat.room)
  seats?: RoomSeat[];

  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  createdAt!: Date;

  @Column({ name: 'last_activity_at', type: 'timestamptz' })
  lastActivityAt!: Date;

  @Index()
  @Column({ name: 'expires_at', type: 'timestamptz' })
  expiresAt!: Date;
}
